"""Prepares the recordings: every frame with its time, so the film shows the last frame with pts <= t.

Usage: venv/bin/python -I clips.py <clips_folder> <material_folder>
Accepts .mp4, .webm and .mkv (constant or variable frame rate). If the video is not 1080 x 2400 it is
scaled to that size (Lanczos), which is the size the crops use. Writes <material>/frames/<clip>/NNNNN.jpg
and <material>/clips.js (the CLIPS object for the film).
"""
import json
import os
import subprocess
import sys

videos, material = sys.argv[1], sys.argv[2]
out = {}
for name in sorted(os.listdir(videos)):
    base, ext = os.path.splitext(name)
    if ext not in (".mp4", ".webm", ".mkv") or base.endswith("-discard"):
        continue
    clip = base
    path = os.path.join(videos, name)
    pts = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v", "-show_entries", "frame=pts_time", "-of", "csv=p=0", path],
        capture_output=True, text=True, check=True,
    ).stdout.split()
    times = [round(float(p), 4) for p in pts if p and p != "N/A"]
    folder = os.path.join(material, "frames", clip)
    os.makedirs(folder, exist_ok=True)
    size = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v", "-show_entries", "stream=width,height", "-of", "csv=p=0", path],
                          capture_output=True, text=True, check=True).stdout.strip().split(",")
    scale = [] if size[:2] == ["1080", "2400"] else ["-vf", "scale=1080:2400:flags=lanczos"]
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", "-i", path, "-fps_mode", "passthrough", *scale, "-q:v", "2",
         "-start_number", "0", os.path.join(folder, "%05d.jpg")],
        check=True,
    )
    n = len([f for f in os.listdir(folder) if f.endswith(".jpg")])
    taps_path = os.path.join(videos, clip + ".taps.json")
    taps = json.load(open(taps_path)) if os.path.exists(taps_path) else []
    out[clip] = {"n": n, "times": times[:n], "taps": taps, "duration": times[n - 1] if n else 0}
    print(f"{clip}: {n} frames ({size[0]}x{size[1]}), {len(times)} pts, from {times[0]:.3f} to {times[-1]:.3f} s, {len(taps)} taps")
with open(os.path.join(material, "clips.js"), "w") as f:
    f.write("// Generated by scripts/clips.py: unique frames of every recording and their times.\n")
    f.write("const CLIPS = " + json.dumps(out, ensure_ascii=False) + ";\n")
